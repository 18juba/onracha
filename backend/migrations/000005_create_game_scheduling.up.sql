CREATE TABLE arena_time_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    arena_id BIGINT NOT NULL REFERENCES arenas (id) ON DELETE CASCADE,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT arena_time_slots_positive_duration CHECK (ends_at > starts_at),
    CONSTRAINT arena_time_slots_unique_interval UNIQUE (arena_id, starts_at, ends_at)
);

CREATE INDEX arena_time_slots_arena_start_idx ON arena_time_slots (arena_id, starts_at);

CREATE TABLE games (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_slot_id BIGINT NOT NULL UNIQUE REFERENCES arena_time_slots (id) ON DELETE RESTRICT,
    organizer_user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE game_participants (
    game_id BIGINT NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (game_id, user_id)
);

CREATE INDEX game_participants_user_id_idx ON game_participants (user_id, game_id);
